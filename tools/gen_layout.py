#!/usr/bin/env python3
"""layout.conf for mpc-vst-plugins: the eight tabs and their Q-Links, from tools/panel.py.

    python3 tools/gen_layout.py --write     (writes layout.conf)
    python3 tools/gen_layout.py --check     (fails when layout.conf is stale; build.sh runs it)

The framework's skin generator only needs each tab's controls (here placeholders) and its qlinks lines; tools/skin.py
then draws every page from tools/panel.py and tools/art.py and replaces the placeholders.

Q-Links (the rule kept since PlateauXXL's first Force test): every control of a page is on a Q-Link, in reading
order (top row left to right, then the next row), at most 16 per Q-Link sub-page; the Act select comes last
(where a page's controls fill a whole bank, it stays on the header's buttons only). The
step cells are touch targets, not Q-Links (the STEP knob and the PAGE buttons reach every step)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import panel as P  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "layout.conf")
MAX = 16


def page_keys(tab):
    """the page's Q-Link keys: its controls in reading order, then the Act select when it still fits the bank"""
    keys = P.keys_in_reading_order(tab)
    return keys + ["act"] if len(keys) % MAX != 0 else keys


def qlink_pages(tab):
    keys = page_keys(tab)
    pages = [keys[i:i + MAX] for i in range(0, len(keys), MAX)]
    if len(pages) == 1:
        return [(tab, pages[0])]
    return [("%s %d" % (tab, i + 1), k) for i, k in enumerate(pages)]


def text():
    out = ["# Loop-SaboteurXXL -- page layout (mpc-vst-plugins layout.conf syntax: tools/shadow_skin.py).",
           "# GENERATED by tools/gen_layout.py from tools/panel.py; tools/skin.py draws the pages and replaces the",
           "# placeholder controls below. Edit tools/panel.py, then run `python3 tools/gen_layout.py --write`.",
           "theme_bg=1a1a1a", "theme_panel=1a1a1a", "theme_ink=ebebf0", "theme_ink_dim=8c8c96",
           "theme_accent=ff5a3c", "theme_knob_ring=ff5a3c", "theme_seg_active=ff5a3c", ""]
    first = qlink_pages(P.TABS[0])[0][1]
    out.append("qlinks_track = " + ",".join(first))
    out.append("")
    for tab in P.TABS:
        out.append("[tab %s]" % tab)
        keys = page_keys(tab)
        for i, k in enumerate(keys):
            out.append('knob cx=%d cy=%d r=12 label="" key=%s ns=0 bw=30' % (24 + (i % 36) * 34, 110 + (i // 36) * 40, k))
        for name, ks in qlink_pages(tab):
            out.append('qlinks "%s" = %s' % (name, ",".join(ks)))
        out.append("")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    t = text()
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != t:
            sys.exit("layout.conf is stale: run python3 tools/gen_layout.py --write")
    else:
        open(OUT, "w").write(t)
        print("layout.conf written")
